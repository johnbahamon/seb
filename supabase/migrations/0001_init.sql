-- ---------------------------------------------------------------------------
-- Catálogo de repuestos Groupe SEB — esquema inicial (Postgres / Supabase)
--
-- Dos capas, y esa separación es el corazón del diseño:
--
--   BASE     tablas que escribe el pipeline de Python (PDF + API AgoraPlus).
--   OVERRIDE tablas que sólo escribe una persona desde /admin.
--            El importador NUNCA las abre, así que una edición manual no se
--            puede perder por un upsert descuidado: la protección es una
--            frontera de tablas, no una regla que alguien deba recordar.
--
-- Cuando el pipeline cambia un valor que además fue editado a mano, no gana
-- nadie en silencio: v_drift lo saca a una cola de revisión.
--
-- Cifras reales verificadas sobre public/data/catalog.json:
--   552 modelos · 1737 repuestos · 18 familias (15 en modelos + 3 sólo en
--   repuestos) · 8 marcas · 834 láminas · 1646 repuestos con precio.
-- ---------------------------------------------------------------------------

-- ============================================================ utilidades

-- `default now()` sólo dispara en INSERT, y los upsert de PostgREST llegan
-- como INSERT ... ON CONFLICT DO UPDATE: sin esto las marcas de tiempo
-- quedarían congeladas en la primera carga.
create or replace function touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- =========================================================== catálogos base
